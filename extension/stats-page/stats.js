/**
 * Render chart for a single image
 */
function renderImageChart(image, timeRange) {
  const canvasId = `image-chart-${image.id}`;
  const canvas = document.getElementById(canvasId);
  if (!canvas) return;

  const ctx = canvas.getContext('2d');

  // Destroy existing chart if any
  if (imageCharts.has(image.id)) {
    imageCharts.get(image.id).destroy();
  }

  const resolvedFull = resolveSnapshots(image.snapshots || []);
  const chartType = getEffectiveChartType(timeRange, imageChartTypes.get(image.id));
  const isArea = chartType === 'area';
  const deltaMode = !isArea && isDeltaMode(timeRange);
  const stacked = (deltaMode && chartType === 'bar') || isArea;
  const timeAxis = !deltaMode && (chartType === 'line' || isArea);

  const inRange = filterByTimeRange(resolvedFull, timeRange);
  if (inRange.length < 2) {
    // Not enough data points
    canvas.style.display = 'none';
    const wrapper = canvas.closest('.image-chart-wrapper');
    if (!wrapper.querySelector('.image-chart-empty')) {
      wrapper.innerHTML = '<div class="image-chart-empty">Not enough data for selected time range</div>';
    }
    return;
  }

  canvas.style.display = 'block';
  const wrapper = canvas.closest('.image-chart-wrapper');
  const emptyMsg = wrapper.querySelector('.image-chart-empty');
  if (emptyMsg) emptyMsg.remove();

  const vis = imageLineVisibility;
  const REACTION_SERIES = [
    ['likes', 'Likes'],
    ['hearts', 'Hearts'],
    ['laughs', 'Laughs'],
    ['cries', 'Cries']
  ];
  const EXTRA_SERIES = [
    ['comments', 'Comments'],
    ['buzz', 'Buzz'],
    ['collects', 'Collects']
  ];

  // Bounded ranges re-baseline cumulative views to 0 at the window start.
  const windowed = rebaseWindow(resolvedFull, timeRange);

  let labels;
  const datasets = [];

  if (isArea) {
    // AoE2-style stacked bands of this image's series (reactions + extras).
    for (const [key, label] of [...REACTION_SERIES, ...EXTRA_SERIES]) {
      if (!vis[key]) continue;
      datasets.push({
        label,
        data: windowed.map(s => ({ x: new Date(s.timestamp).getTime(), y: s[key] || 0 })),
        borderColor: CHART_COLORS[key],
        backgroundColor: CHART_COLORS[key] + 'CC',
        borderWidth: 1,
        stepped: 'before',
        tension: 0,
        fill: true,
        stack: 'shown',
        pointRadius: 0,
        pointHoverRadius: 3
      });
    }
    if (vis.total) {
      datasets.push({
        label: 'Total',
        data: windowed.map(s => ({
          x: new Date(s.timestamp).getTime(),
          y: (s.likes || 0) + (s.hearts || 0) + (s.laughs || 0) + (s.cries || 0)
        })),
        borderColor: CHART_COLORS.total,
        borderWidth: 2,
        stepped: 'before',
        tension: 0,
        fill: false,
        stack: '__total',
        pointRadius: 0,
        pointHoverRadius: 3
      });
    }
  } else if (deltaMode) {
    const buckets = bucketedDeltas(resolvedFull, timeRange);
    labels = buckets.map(b => formatChartDate(new Date(b.timestamp), timeRange));

    const barDataset = (key, label, stack) => ({
      label,
      data: buckets.map(b => b[key] || 0),
      backgroundColor: CHART_COLORS[key],
      stack,
      borderColor: CHART_SURFACE,
      borderWidth: 1,
      borderSkipped: false,
      borderRadius: 2,
      maxBarThickness: 20
    });
    const lineDataset = (key, label, width) => ({
      label,
      data: buckets.map(b => b[key] || 0),
      borderColor: CHART_COLORS[key],
      borderWidth: width,
      tension: 0,
      fill: false,
      pointRadius: 0,
      pointHoverRadius: 3
    });

    if (!stacked && vis.total) {
      datasets.push(lineDataset('total', 'Total', 2));
      datasets[datasets.length - 1].data =
        buckets.map(b => (b.likes || 0) + (b.hearts || 0) + (b.laughs || 0) + (b.cries || 0));
    }
    for (const [key, label] of REACTION_SERIES) {
      if (!vis[key]) continue;
      datasets.push(stacked ? barDataset(key, label, 'reactions') : lineDataset(key, label, 1.5));
    }
    for (const [key, label] of EXTRA_SERIES) {
      if (!vis[key]) continue;
      datasets.push(stacked ? barDataset(key, label, key) : lineDataset(key, label, 1.5));
    }
  } else if (chartType === 'bar') {
    labels = windowed.map(s => formatChartDate(new Date(s.timestamp), timeRange));
    const push = (key, label) => datasets.push({
      label,
      data: windowed.map(s => key === 'total' ? getTotalReactions(s) : (s[key] || 0)),
      backgroundColor: CHART_COLORS[key],
      borderColor: CHART_SURFACE,
      borderWidth: 1,
      borderSkipped: false,
      borderRadius: 2,
      maxBarThickness: 20
    });
    if (vis.total) push('total', 'Total');
    for (const [key, label] of [...REACTION_SERIES, ...EXTRA_SERIES]) {
      if (vis[key]) push(key, label);
    }
  } else {
    // Cumulative stepped lines on a true time axis (rebased for bounded ranges)
    const push = (key, label, width) => datasets.push({
      label,
      data: windowed.map(s => ({
        x: new Date(s.timestamp).getTime(),
        y: key === 'total' ? getTotalReactions(s) : (s[key] || 0)
      })),
      borderColor: CHART_COLORS[key],
      borderWidth: width,
      stepped: 'before',
      tension: 0,
      fill: false,
      pointRadius: 0,
      pointHoverRadius: 3
    });
    if (vis.total) push('total', 'Total', 2);
    for (const [key, label] of [...REACTION_SERIES, ...EXTRA_SERIES]) {
      if (vis[key]) push(key, label, 1.5);
    }
  }

  const xScale = timeAxis
    ? {
        type: 'linear',
        display: false,
        min: timeRange === 'all' ? undefined : Date.now() - TIME_RANGE_MS[timeRange],
        max: timeRange === 'all' ? undefined : Date.now()
      }
    : { display: false, stacked };

  const chart = new Chart(ctx, {
    type: isArea ? 'line' : chartType,
    data: {
      labels,
      datasets
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      interaction: {
        mode: 'index',
        intersect: false
      },
      plugins: {
        legend: {
          display: false
        },
        tooltip: {
          backgroundColor: '#25262b',
          titleColor: '#fff',
          bodyColor: '#c1c2c5',
          footerColor: '#fff',
          borderColor: '#373a40',
          borderWidth: 1,
          padding: 8,
          displayColors: true,
          callbacks: {
            title: function(items) {
              if (!items.length) return '';
              if (timeAxis) {
                return formatDate(new Date(items[0].parsed.x));
              }
              return items[0].label;
            },
            label: function(context) {
              const emoji = LABEL_EMOJI[context.dataset.label] || context.dataset.label;
              const value = context.parsed.y.toLocaleString();
              if (deltaMode) {
                return `${emoji}: +${value}`;
              }
              const idx = context.dataIndex;
              let delta = '';
              if (idx > 0) {
                const prevPoint = context.dataset.data[idx - 1];
                const prev = (prevPoint && typeof prevPoint === 'object') ? prevPoint.y : prevPoint;
                const diff = context.parsed.y - prev;
                if (diff !== 0) {
                  delta = ` (${diff >= 0 ? '+' : ''}${diff.toLocaleString()})`;
                }
              }
              return `${emoji}: ${value}${delta}`;
            },
            footer: function(items) {
              if (!stacked) return '';
              const total = items
                .filter(i => i.dataset.stack === 'reactions' || i.dataset.stack === 'shown')
                .reduce((sum, i) => sum + i.parsed.y, 0);
              if (total <= 0) return '';
              const gained = deltaMode || timeRange !== 'all';
              const word = isArea ? 'Shown' : 'Total';
              return `${word}: ${gained ? '+' : ''}${total.toLocaleString()}`;
            }
          }
        }
      },
      scales: {
        x: xScale,
        y: {
          stacked,
          grid: {
            color: 'rgba(55, 58, 64, 0.3)',
            drawBorder: false
          },
          ticks: {
            color: '#909296',
            font: { size: 10 },
            callback: value => formatNumber(value)
          },
          beginAtZero: true,
          title: deltaMode ? {
            display: true,
            text: 'Gained per period',
            color: '#909296',
            font: { size: 10 }
          } : { display: false }
        }
      }
    }
  });

  imageCharts.set(image.id, chart);
}

/**
 * Sort images
 */
function sortImages(images, sortBy) {
  switch (sortBy) {
    case 'oldest':
      return images.sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));
    case 'reactions': {
      const reactionType = document.getElementById('reactionTypeSelect')?.value || 'total';
      if (reactionType === 'total') {
        return images.sort((a, b) => getTotalReactions(getCurrentStats(b)) - getTotalReactions(getCurrentStats(a)));
      }
      return images.sort((a, b) => (getCurrentStats(b)[reactionType] || 0) - (getCurrentStats(a)[reactionType] || 0));
    }
    case 'comments':
      return images.sort((a, b) => (getCurrentStats(b).comments || 0) - (getCurrentStats(a).comments || 0));
    case 'newest':
    default:
      return images.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));
  }
}

/**
 * Get current stats from an image (latest snapshot or legacy currentStats)
 */
function getCurrentStats(image) {
  // Support new snapshots format — resolve deltas to get absolute values
  if (image.snapshots && image.snapshots.length > 0) {
    const resolved = resolveSnapshots(image.snapshots);
    return resolved[resolved.length - 1];
  }
  // Fallback to legacy format
  return image.currentStats || { likes: 0, hearts: 0, laughs: 0, cries: 0, comments: 0, buzz: 0, collects: 0, views: 0 };
}

/**
 * Get total reactions for an image
 */
function getTotalReactions(stats) {
  if (!stats) return 0;
  return (stats.likes || 0) + (stats.hearts || 0) + (stats.laughs || 0) + (stats.cries || 0);
}

/**
 * Compute period summary: total gains by type and per-image gains for the current time range
 */
function computePeriodSummary(timeRange) {
  if (!statsData || !statsData.images) return null;

  const types = ['likes', 'hearts', 'laughs', 'cries', 'comments', 'buzz', 'collects'];
  const totals = { total: 0 };
  types.forEach(t => totals[t] = 0);

  const imageGains = [];

  for (const image of statsData.images) {
    if (!image.snapshots || image.snapshots.length === 0) continue;

    const resolved = resolveSnapshots(image.snapshots);
    const filtered = filterByTimeRange(resolved, timeRange);
    if (filtered.length < (timeRange === 'all' ? 1 : 2)) continue;

    // For "all" time, use zero baseline so we show absolute totals (matching summary cards)
    const first = timeRange === 'all'
      ? { likes: 0, hearts: 0, laughs: 0, cries: 0, comments: 0, buzz: 0, collects: 0 }
      : filtered[0];
    const last = filtered[filtered.length - 1];

    const gains = {};
    let totalGain = 0;
    for (const t of types) {
      const g = Math.max(0, (last[t] || 0) - (first[t] || 0));
      gains[t] = g;
      totals[t] += g;
      if (t !== 'comments' && t !== 'buzz' && t !== 'collects') totalGain += g;
    }

    if (totalGain > 0) {
      imageGains.push({ image, gains, totalGain });
      totals.total += totalGain;
    }
  }

  imageGains.sort((a, b) => b.totalGain - a.totalGain);

  return { totals, images: imageGains };
}

/**
 * Render the period summary ribbon below the overview chart
 */
function renderPeriodSummary() {
  const container = document.getElementById('periodSummary');
  if (!container) return;

  const summary = computePeriodSummary(currentTimeRange);

  if (!summary || summary.images.length === 0) {
    container.innerHTML = '<div class="period-summary-empty">No data for this period</div>';
    return;
  }

  const emojiMap = {
    total: '\u{1F310}',
    likes: '\u{1F44D}', hearts: '\u2764\uFE0F', laughs: '\u{1F604}',
    cries: '\u{1F622}', comments: '\u{1F4AC}', buzz: '\u26A1', collects: '\u{1F516}'
  };

  const sortType = currentPeriodSort;
  const sortLabel = sortType === 'total' ? 'reactions' : sortType;

  // Sort images by selected type
  let sortedImages;
  if (sortType === 'total') {
    sortedImages = [...summary.images].sort((a, b) => b.totalGain - a.totalGain);
  } else {
    sortedImages = [...summary.images]
      .filter(item => (item.gains[sortType] || 0) > 0)
      .sort((a, b) => (b.gains[sortType] || 0) - (a.gains[sortType] || 0));
  }

  // Gains row — Total badge always shown first, others only if > 0
  const badgeTypes = ['total', ...Object.keys(summary.totals).filter(t => t !== 'total')];
  const badgesHtml = badgeTypes
    .filter(type => type === 'total' || summary.totals[type] > 0)
    .map(type => {
      const val = summary.totals[type];
      const active = type === sortType ? ' active' : '';
      return `<span class="period-badge ${type}${active}" data-sort="${type}">${emojiMap[type]} <strong>+${formatNumber(val)}</strong></span>`;
    }).join('');

  // Top 5 images
  const top5 = sortedImages.slice(0, 5);
  const rest = sortedImages.slice(5);

  const topImagesHtml = top5.map(item => {
    const img = item.image;
    const thumb = img.thumbnailUrl
      ? `<img src="${escapeHtml(safeCivitaiUrl(img.thumbnailUrl, ''))}" alt="" loading="lazy">`
      : '<div class="placeholder">?</div>';
    const name = escapeHtml(displayName(img));
    const gainValue = sortType === 'total' ? item.totalGain : (item.gains[sortType] || 0);
    return `
      <a class="period-top-image" href="${escapeHtml(safeCivitaiUrl(img.url))}" target="_blank" rel="noopener">
        <div class="period-top-thumb">${thumb}</div>
        <div class="period-top-info">
          <span class="period-top-name" title="${name}">${name}</span>
          <span class="period-top-gain">+${formatNumber(gainValue)} ${sortLabel}</span>
        </div>
      </a>`;
  }).join('');

  // "+N more" tooltip
  let moreHtml = '';
  if (rest.length > 0) {
    const tooltipItems = rest.map(item => {
      const name = escapeHtml(displayName(item.image));
      const gainValue = sortType === 'total' ? item.totalGain : (item.gains[sortType] || 0);
      return `<div class="period-more-item"><span>${name}</span><span>+${formatNumber(gainValue)} ${sortLabel}</span></div>`;
    }).join('');

    moreHtml = `
      <div class="period-more-wrapper">
        <span class="period-badge period-more-badge">+${rest.length} more</span>
        <div class="period-more-tooltip">${tooltipItems}</div>
      </div>`;
  }

  container.innerHTML = `
    <div class="period-gains-row">${badgesHtml}</div>
    <div class="period-top-images">
      ${topImagesHtml}
      ${moreHtml}
    </div>`;

  // Attach click handlers to sortable badges
  container.querySelectorAll('.period-badge[data-sort]').forEach(badge => {
    badge.addEventListener('click', () => {
      currentPeriodSort = badge.dataset.sort;
      renderPeriodSummary();
    });
  });
}

