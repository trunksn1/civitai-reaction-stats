/**
 * Index images by post so sibling images can be counted and numbered.
 * Rebuilt whenever stats data changes; keyed by post id.
 *
 * Ordering is by image id ascending, NOT createdAt: sibling images routinely
 * share one timestamp (a whole post publishes at once), and in some older posts
 * the createdAt order contradicts the id order. Id is the only stable key.
 */
function rebuildPostIndex() {
  postIndex = new Map();
  if (!statsData || !statsData.images) return;

  for (const image of statsData.images) {
    if (image.postId == null) continue;
    const key = String(image.postId);
    if (!postIndex.has(key)) postIndex.set(key, []);
    postIndex.get(key).push(image);
  }
  for (const siblings of postIndex.values()) {
    siblings.sort((a, b) => Number(a.id) - Number(b.id));
  }
}

/**
 * Where an image sits within its post: { index, total }, 1-based. Returns null
 * for a single-image post — nothing to number.
 */
function postPosition(image) {
  if (image.postId == null) return null;
  const siblings = postIndex.get(String(image.postId));
  if (!siblings || siblings.length < 2) return null;
  const index = siblings.findIndex(img => img.id === image.id);
  if (index === -1) return null;
  return { index: index + 1, total: siblings.length };
}

/** The collector's title for an image's post, or null. */
function postTitleOf(image) {
  if (image.postId == null || !statsData || !statsData.postTitles) return null;
  const entry = statsData.postTitles[String(image.postId)];
  return entry && entry.title ? entry.title : null;
}

/** Append " — pt. N" when the image is one of several in its post. */
function withPartSuffix(baseName, image) {
  const position = postPosition(image);
  return position ? `${baseName} — pt. ${position.index}` : baseName;
}

/**
 * The name to show for an image everywhere in the UI. First rung that produces
 * something wins:
 *
 *   1. a name the user set on this image alone
 *   2. a name the user spread across the whole post (numbered)
 *   3. the post's title on Civitai (numbered)
 *   4. base model + post date — covers ~98% of images and beats a bare id
 *   5. the collector's name, which is the id unless generation metadata existed
 *
 * Rungs 3-5 changed in Phase 7: `image.name` is the prompt when Civitai exposes
 * one, but `meta` comes back null for every image on this account, so before
 * this cascade existed every card read "Image 114507519".
 */
function displayName(image) {
  const ownName = customImageNames[image.id];
  if (ownName) return ownName;

  if (image.postId != null) {
    const postName = customPostNames[String(image.postId)];
    if (postName) return withPartSuffix(postName, image);
  }

  return automaticName(image);
}

/**
 * The name an image would have with every user override removed — rungs 3-5.
 * Used as the rename field's placeholder and as the "typed the default back in,
 * so drop the override" comparison.
 */
function automaticName(image) {
  const title = postTitleOf(image);
  if (title) return withPartSuffix(title, image);

  if (image.baseModel && image.createdAt) {
    return `${image.baseModel} · ${formatShortDate(new Date(image.createdAt))}`;
  }

  return image.name || `Image ${image.id}`;
}

/**
 * Hover text for a card's name: says where the name came from, so a renamed
 * card doesn't hide which post it belongs to.
 */
function nameTooltip(image) {
  const parts = [`Image ${image.id}`];
  const position = postPosition(image);

  if (image.postId != null) {
    parts.push(position
      ? `Post ${image.postId} (${position.index} of ${position.total})`
      : `Post ${image.postId}`);
  }

  const title = postTitleOf(image);
  parts.push(title ? `Post title: "${title}"` : 'Post has no title on Civitai');

  if (customImageNames[image.id]) parts.push('Renamed here (this image only)');
  else if (image.postId != null && customPostNames[String(image.postId)]) parts.push('Renamed here (whole post)');

  return parts.join('\n');
}

/**
 * Commit a rename. Where the name lands depends on whether the image has
 * siblings in its post, and — when it does — on what the user picks.
 *
 * Note the asymmetry with Civitai: a post there has exactly one title shared by
 * all its images, so "pt. 1 / pt. 2" is a numbering this extension applies for
 * display and never something that could be stored upstream per image.
 */
function applyLocalRename(image, value, original, scope) {
  const postId = image.postId != null ? String(image.postId) : null;
  const base = value.replace(/\s+[—-]\s*pt\.\s*\d+\s*$/i, '').trim() || value;

  if (scope === 'post' && postId !== null) {
    delete customImageNames[image.id];
    if (!value || value === original || base === postTitleOf(image)) delete customPostNames[postId];
    else customPostNames[postId] = base;
  } else {
    if (!value || value === original) delete customImageNames[image.id];
    else customImageNames[image.id] = value;
  }
}

function requestRename(image) {
  const dialog = document.getElementById('renameDialog');
  const form = document.getElementById('renameForm');
  const input = document.getElementById('renameInput');
  const postScope = document.getElementById('renamePostScope');
  const publicOption = document.getElementById('renamePublicOption');
  const publicCheckbox = document.getElementById('renamePublic');
  const warning = document.getElementById('renameWarning');
  const position = postPosition(image);
  const hasPost = image.postId != null;

  input.value = displayName(image);
  input.placeholder = automaticName(image);
  document.getElementById('renameDescription').textContent = position
    ? `Post ${image.postId} contains ${position.total} images. Civitai has one public title shared by all of them.`
    : hasPost ? `This image belongs to Civitai post ${image.postId}.` : 'No Civitai post id was collected for this image.';
  postScope.hidden = !hasPost;
  publicOption.hidden = !hasPost;
  warning.hidden = !hasPost;
  publicCheckbox.checked = hasPost;
  form.elements.renameScope.value = hasPost ? 'post' : 'image';

  return new Promise(resolve => {
    form.onsubmit = event => {
      event.preventDefault();
      dialog.close('save');
    };
    document.getElementById('renameCancelBtn').onclick = () => dialog.close('cancel');
    dialog.onclose = () => {
      if (dialog.returnValue !== 'save') {
        resolve(null);
        return;
      }
      resolve({
        value: input.value.trim(),
        scope: form.elements.renameScope.value,
        writePublic: hasPost && publicCheckbox.checked
      });
    };
    dialog.showModal();
    input.focus();
    input.select();
  });
}

function publicTitleFromName(value) {
  if (!value) return null;
  return value.replace(/\s+[—-]\s*pt\.\s*\d+\s*$/i, '').trim() || null;
}

async function writeCivitaiTitle(image, title, expectedPreviousTitle) {
  let response = await chrome.runtime.sendMessage({
    action: 'updateCivitaiPostTitle',
    postId: image.postId,
    host: image.host || 'com',
    title,
    expectedPreviousTitle
  });
  if (!response.success) throw new Error(response.error || 'Civitai title update failed.');

  if (response.conflict) {
    const current = response.currentTitle || '(no title)';
    const overwrite = confirm(
      `The public Civitai title changed since this data was collected.\n\n` +
      `Current title: “${current}”\n\nOverwrite it with “${title || '(no title)'}”?`
    );
    if (!overwrite) throw new Error('Public title update canceled because the Civitai title changed.');
    response = await chrome.runtime.sendMessage({
      action: 'updateCivitaiPostTitle',
      postId: image.postId,
      host: image.host || 'com',
      title,
      expectedPreviousTitle: response.currentTitle
    });
    if (!response.success || response.conflict) {
      throw new Error(response.error || 'The title changed again before it could be updated.');
    }
  }
  return response;
}

async function startRename(imageId) {

  const image = statsData && statsData.images
    ? statsData.images.find(img => img.id === imageId)
    : null;
  if (!image) return;

  const request = await requestRename(image);
  if (!request) return;
  const original = automaticName(image);
  let publicError = null;
  if (request.writePublic) {
    const nextTitle = publicTitleFromName(request.value);
    const expectedTitle = postTitleOf(image);
    if (nextTitle !== expectedTitle) {
      try {
        const result = await writeCivitaiTitle(image, nextTitle, expectedTitle);
        statsData.postTitles = statsData.postTitles || {};
        statsData.postTitles[String(image.postId)] = {
          ...(statsData.postTitles[String(image.postId)] || {}),
          title: result.title,
          fetchedAt: new Date().toISOString()
        };
        lastCivitaiTitleWrite = {
          postId: String(image.postId),
          host: image.host || 'com',
          previousTitle: result.previousTitle,
          title: result.title,
          timestamp: new Date().toISOString()
        };
        await chrome.storage.local.set({ lastCivitaiTitleWrite });
      } catch (error) {
        publicError = error;
      }
    }
  }

  applyLocalRename(image, request.value, original, request.scope);
  await saveCustomImageNames();
  renderStats();
  if (publicError) alert(`The local name was saved, but Civitai was not changed.\n\n${publicError.message}`);
}

async function undoLastCivitaiTitle() {
  const undo = lastCivitaiTitleWrite;
  if (!undo) return;
  const image = (statsData.images || []).find(item => String(item.postId) === String(undo.postId));
  if (!image) {
    alert('The post for the last title change is not present in the loaded stats.');
    return;
  }
  if (!confirm(`Restore the public Civitai title to “${undo.previousTitle || '(no title)'}”?`)) return;

  try {
    const result = await writeCivitaiTitle(image, undo.previousTitle, undo.title);
    statsData.postTitles = statsData.postTitles || {};
    statsData.postTitles[String(undo.postId)] = {
      ...(statsData.postTitles[String(undo.postId)] || {}),
      title: result.title,
      fetchedAt: new Date().toISOString()
    };
    lastCivitaiTitleWrite = null;
    await chrome.storage.local.remove('lastCivitaiTitleWrite');
    renderStats();
  } catch (error) {
    alert(`The Civitai title was not undone.\n\n${error.message}`);
  }
}

