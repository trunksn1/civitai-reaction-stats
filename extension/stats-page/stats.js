/**
 * Render the overview chart
 */
function renderChart() {
  const canvas = document.getElementById('overviewChart');
  const ctx = canvas.getContext('2d');

  if (overviewChart) {
    overviewChart.destroy();
  }

  const chartType = getEffectiveChartType(currentTimeRange, currentChartType);
  const isArea = chartType === 'area';
  // Area mode (the AoE2 timeline) is always cumulative stacked, whatever the range.
  const deltaMode = !isArea && isDeltaMode(currentTimeRange);
  const data = getChartData();
  const stacked = !!data.stacked;
  // Cumulative lines run on a true time axis (linear ms) so uneven snapshot
  // spacing renders honestly; bars use evenly-spaced category buckets.
  const timeAxis = !deltaMode && (chartType === 'line' || isArea);
  const logY = !deltaMode && useLogScale && !isArea;

  // Update chart title
  const titleEl = document.getElementById('chartTitle');
  if (titleEl) {
    const bounded = currentTimeRange !== 'all';
    titleEl.textContent = deltaMode
      ? 'Reactions Gained'
      : bounded
        ? (isArea ? 'Gained This Period — stacked' : 'Gained This Period — running total')
        : (isArea ? 'Reactions Over Time — stacked' : 'Reactions Over Time');
  }

  const xScale = timeAxis
    ? {
        type: 'linear',
        min: currentTimeRange === 'all' ? undefined : Date.now() - TIME_RANGE_MS[currentTimeRange],
        max: currentTimeRange === 'all' ? undefined : Date.now(),
        grid: { color: 'rgba(55, 58, 64, 0.5)', drawBorder: false },
        ticks: {
          color: '#909296',
          maxTicksLimit: 8,
          maxRotation: 0,
          callback: value => formatChartDate(new Date(value), currentTimeRange)
        }
      }
    : {
        stacked,
        grid: { color: 'rgba(55, 58, 64, 0.5)', drawBorder: false },
        ticks: { color: '#909296', maxTicksLimit: 8, maxRotation: 0, autoSkip: true }
      };

  overviewChart = new Chart(ctx, {
    type: isArea ? 'line' : chartType,
    data: { labels: data.labels, datasets: data.datasets },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      interaction: {
        mode: 'index',
        intersect: false
      },
      plugins: {
        legend: {
          display: false
        },
        tooltip: {
          backgroundColor: '#25262b',
          titleColor: '#fff',
          bodyColor: '#c1c2c5',
          footerColor: '#fff',
          borderColor: '#373a40',
          borderWidth: 1,
          padding: 12,
          displayColors: true,
          callbacks: {
            title: function(items) {
              if (!items.length) return '';
              if (timeAxis) {
                return formatDate(new Date(items[0].parsed.x));
              }
              return items[0].label;
            },
            label: function(context) {
              const emoji = LABEL_EMOJI[context.dataset.label] || context.dataset.label;
              const value = context.parsed.y.toLocaleString();
              if (deltaMode) {
                return `${emoji}: +${value}`;
              }
              const idx = context.dataIndex;
              let delta = '';
              if (idx > 0) {
                const prevPoint = context.dataset.data[idx - 1];
                const prev = (prevPoint && typeof prevPoint === 'object') ? prevPoint.y : prevPoint;
                const diff = context.parsed.y - prev;
                if (diff !== 0) {
                  delta = ` (${diff >= 0 ? '+' : ''}${diff.toLocaleString()})`;
                }
              }
              return `${emoji}: ${value}${delta}`;
            },
            footer: function(items) {
              // In stacked modes the stack is the total — surface it.
              if (!stacked) return '';
              const total = items
                .filter(i => i.dataset.stack === 'reactions' || i.dataset.stack === 'shown')
                .reduce((sum, i) => sum + i.parsed.y, 0);
              if (total <= 0) return '';
              const gained = deltaMode || currentTimeRange !== 'all';
              const word = isArea ? 'Shown' : 'Total';
              return `${word}: ${gained ? '+' : ''}${total.toLocaleString()}`;
            }
          }
        }
      },
      scales: {
        x: xScale,
        y: {
          stacked,
          type: logY ? 'logarithmic' : 'linear',
          grid: {
            color: 'rgba(55, 58, 64, 0.5)',
            drawBorder: false
          },
          ticks: {
            color: '#909296',
            callback: value => formatNumber(value)
          },
          beginAtZero: !logY,
          title: deltaMode ? {
            display: true,
            text: 'Gained per period',
            color: '#909296',
            font: { size: 12 }
          } : { display: false }
        }
      }
    }
  });
}

