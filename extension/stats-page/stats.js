/**
 * Check if the given time range should use delta mode (reactions gained per period)
 */
function isDeltaMode(timeRange) {
  return ['1d', '7d', '30d', '90d'].includes(timeRange);
}

/**
 * computeDeltas comes from the shared snapshot codec (../lib/snapshot-codec.js,
 * loaded by stats.html before this file) — the same code the collector uses.
 */
const computeDeltas = SnapshotCodec.computeDeltas;

/**
 * Sum per-snapshot gains into FIXED calendar buckets for a time range.
 * Input is the full RESOLVED (absolute) series; output is one entry per bucket
 * from range start to now, zero-filled, each { timestamp, likes, hearts, ... }.
 * A gain between two snapshots is attributed to the bucket of the later one.
 */
function bucketedDeltas(resolvedSnapshots, timeRange) {
  const bucketMs = BUCKET_MS[timeRange];
  const rangeMs = TIME_RANGE_MS[timeRange];
  if (!bucketMs || !rangeMs) return [];

  const now = Date.now();
  const start = Math.floor((now - rangeMs) / bucketMs) * bucketMs;

  const buckets = [];
  for (let t = start; t <= now; t += bucketMs) {
    const b = { timestamp: new Date(t).toISOString() };
    for (const [key] of SnapshotCodec.FIELDS) b[key] = 0;
    buckets.push(b);
  }

  const deltas = computeDeltas(resolvedSnapshots);
  for (const d of deltas) {
    const ts = new Date(d.timestamp).getTime();
    if (ts < start || ts > now) continue;
    const idx = Math.floor((ts - start) / bucketMs);
    const b = buckets[idx];
    if (!b) continue;
    for (const [key] of SnapshotCodec.FIELDS) b[key] += d[key] || 0;
  }

  return buckets;
}

/**
 * Re-baseline a RESOLVED series to a bounded time window: every field becomes
 * "gained since the window start" (value minus the last value at or before the
 * start; 0 with no prior history), clamped at 0. A 7d chart therefore starts
 * at 0 and shows the week's growth instead of zooming a 51k cumulative wall.
 * Adds an anchor point at the window start and a terminal point at now so
 * stepped lines span the full window. Returns the input unchanged for 'all'.
 */
function rebaseWindow(resolvedSnapshots, timeRange) {
  if (timeRange === 'all' || !TIME_RANGE_MS[timeRange]) return resolvedSnapshots;

  const start = Date.now() - TIME_RANGE_MS[timeRange];
  let baseline = null;
  const windowed = [];
  for (const s of resolvedSnapshots) {
    if (new Date(s.timestamp).getTime() <= start) {
      baseline = s;
    } else {
      windowed.push(s);
    }
  }

  const base = {};
  for (const [key] of SnapshotCodec.FIELDS) base[key] = baseline ? (baseline[key] || 0) : 0;

  const out = [];
  const anchor = { timestamp: new Date(start).toISOString() };
  for (const [key] of SnapshotCodec.FIELDS) anchor[key] = 0;
  out.push(anchor);

  for (const s of windowed) {
    const r = { timestamp: s.timestamp };
    for (const [key] of SnapshotCodec.FIELDS) r[key] = Math.max(0, (s[key] || 0) - base[key]);
    out.push(r);
  }

  // Terminal point: hold the last value through to "now"
  const last = out[out.length - 1];
  const terminal = { ...last, timestamp: new Date().toISOString() };
  out.push(terminal);

  return out;
}

/**
 * Get effective chart type based on time range and user override.
 * 'auto' = bar for delta mode, line for cumulative.
 */
function getEffectiveChartType(timeRange, override) {
  if (override && override !== 'auto') return override;
  return isDeltaMode(timeRange) ? 'bar' : 'line';
}

